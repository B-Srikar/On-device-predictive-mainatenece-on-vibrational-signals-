        [(98, "Baseline end", "#2E7D32"), (196, "Cal end (eval >= 196)", "#B7950B")],
        ROOT / "outputs/plots/stage7_ims_ch1.png",
        ROOT / "outputs/plots/stage7_ims_ch1.gif",
        eval_start=196,
