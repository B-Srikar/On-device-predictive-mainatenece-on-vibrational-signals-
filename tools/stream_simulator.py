class HiMonitorOutput(ctypes.Structure):
    _fields_ = [
        ("gated", ctypes.c_int),
        ("raw_hi", ctypes.c_float),
        ("ema_hi", ctypes.c_float),
        ("slope_valid", ctypes.c_int),
        ("slope", ctypes.c_float),
        ("fixed_alarm", ctypes.c_int),
        ("slope_alarm", ctypes.c_int),
    ]


def load_shared_lib(path: Path, n_features: int) -> tuple[ctypes.CDLL, type]:
    """Load libhi_*.dylib and configure exact ctypes signatures."""
    class HiFeatures(ctypes.Structure):
        _fields_ = [("value", ctypes.c_float * n_features)]

    lib = ctypes.CDLL(str(path))
    lib.hi_stream_sizeof.argtypes = []
    lib.hi_stream_sizeof.restype = ctypes.c_size_t
    lib.hi_stream_init_default.argtypes = [ctypes.c_void_p]
    lib.hi_stream_init_default.restype = None
    lib.hi_stream_push.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_float), ctypes.c_size_t]
    lib.hi_stream_push.restype = ctypes.c_int
    lib.hi_stream_latest.argtypes = [
        ctypes.c_void_p,
        ctypes.POINTER(HiFeatures),
        ctypes.POINTER(HiMonitorOutput),
    ]
    lib.hi_stream_latest.restype = ctypes.c_int
    return lib, HiFeatures


def load_cwru_3200_stream(filename: str, label: str, n_windows: int, cfg: dict[str, Any]) -> np.ndarray:
    """Return float32 sample array producing exact `n_windows` overlapping 512-hop windows."""
    raw_sig, _ = de_signal_and_metadata(ROOT / "data/raw/cwru" / filename)
    src_rate = int(cfg["source_sampling_rates"][filename])
    sig, _ = matched_rate_signal(
        raw_sig, filename, label, src_rate, int(cfg["sampling_rate"]), int(cfg["target_rate"])
    )
    need_samples = WINDOW_SIZE + (n_windows - 1) * HOP_SIZE
    if sig.size < need_samples:
        raise ValueError(f"{filename}: has {sig.size} samples, need {need_samples}")
    return np.ascontiguousarray(sig[:need_samples], dtype=np.float32)


def load_ims_ch1_waveforms(bin_path: Path) -> np.ndarray:
    """Read raw Ch 1 waveform snapshots generated by Stage 6b (0..981)."""
    with bin_path.open("rb") as handle:
        n_snaps, n_samp = struct.unpack("<II", handle.read(8))
        data = np.frombuffer(handle.read(n_snaps * n_samp * 4), dtype=np.float32)
    return data.reshape((n_snaps, n_samp)).copy()


def python_cwru_reference(
    stream_f32: np.ndarray,
    cfg: dict[str, Any],
    stats: dict[str, Any],
) -> dict[str, np.ndarray]:
    """Run exact Python reference on the concatenated float32 sample stream."""
    mean: np.ndarray = stats["mean"]
    std: np.ndarray = stats["std"]
    med_rms = float(stats["median_rms"])
    hi_thr = float(stats["hi_threshold"])
    hi_base_mean = float(stats["hi_baseline_mean"])
    alpha = float(cfg["ema_alpha"])
    off_ratio = float(cfg["ims_machine_off_rms_ratio"])
    w_slope = int(cfg["ims_slope_window"])
    consec_req = int(cfg["ims_consecutive_alarms"])
    bands = cfg["fft_bands_hz"]
    rate = int(cfg["target_rate"])
    rms_gate = off_ratio * med_rms
    slope_thr = float(stats["slope_threshold"])

    x_idx = np.arange(w_slope, dtype=float)
    x_c = x_idx - x_idx.mean()
    denom = float(np.sum(x_c ** 2))

    ema_init = False
    ema_hi = 0.0
    ring: list[float] = []
    fix_c, slp_c = 0, 0

    gated_arr, raw_arr, ema_arr, fix_arr, slp_arr = [], [], [], [], []
    for win in window_signal(stream_f32.astype(float), WINDOW_SIZE, float(cfg["overlap"])):
        rf = extract_features(win, rate, bands)
        fvec = np.array(
            [rf["rms"], rf["peak_to_peak"], rf["crest_factor"], rf["kurtosis"]]
            + [float(np.log(max(rf[c], EPSILON))) for c in RAW_BAND_COLS_3200],
            dtype=float,
        )
        if fvec[0] < rms_gate:
            gated_arr.append(1)
            raw_arr.append(0.0)
            ema_arr.append(ema_hi)
            fix_c = 0
            slp_c = 0
            fix_arr.append(0)
            slp_arr.append(0)
            continue
        gated_arr.append(0)
        z = np.maximum((fvec - mean) / np.maximum(std, float(cfg["hi_sigma_floor"])), 0.0)
        raw_hi = float(np.sqrt(np.mean(np.log1p(z) ** 2)))
        if not ema_init:
            ema_init = True
            ema_hi = raw_hi
        else:
            ema_hi = alpha * raw_hi + (1.0 - alpha) * ema_hi
        ring.append(ema_hi)
        if len(ring) > w_slope:
            ring.pop(0)
        slp_ok = False
        if len(ring) == w_slope:
            y = np.array(ring, dtype=float)
            slp = float(np.sum(x_c * (y - y.mean())) / denom)
            slp_ok = (slp > slope_thr) and (ema_hi > hi_base_mean)
        fix_c = min(fix_c + 1, consec_req) if ema_hi > hi_thr else 0
        slp_c = min(slp_c + 1, consec_req) if slp_ok else 0
        raw_arr.append(raw_hi)
        ema_arr.append(ema_hi)
        fix_arr.append(1 if fix_c >= consec_req else 0)
        slp_arr.append(1 if slp_c >= consec_req else 0)

    return {
        "gated": np.asarray(gated_arr, dtype=int),
        "raw_hi": np.asarray(raw_arr, dtype=float),
        "ema_hi": np.asarray(ema_arr, dtype=float),
        "fixed_alarm": np.asarray(fix_arr, dtype=int),
        "slope_alarm": np.asarray(slp_arr, dtype=int),
    }


def python_ims_reference(exp_bin: Path, n_limit: int | None = None) -> dict[str, np.ndarray]:
    """Read Stage 6b Python IMS expectations directly."""
    with exp_bin.open("rb") as handle:
        n_snaps, _, hi_thr, _ = struct.unpack("<Ifff", handle.read(16))
        count = n_snaps if n_limit is None else min(n_snaps, n_limit)
        raw_arr, ema_arr, fix_arr, slp_arr = [], [], [], []
        for _ in range(count):
            _feats = handle.read(9 * 4)
            py_raw, py_ema, _slp, _sv, py_fix, py_slp_al = struct.unpack("<fffiii", handle.read(24))
            raw_arr.append(py_raw)
            ema_arr.append(py_ema)
            fix_arr.append(py_fix)
            slp_arr.append(py_slp_al)
    return {
        "gated": np.zeros(count, dtype=int),
        "raw_hi": np.asarray(raw_arr, dtype=float),
        "ema_hi": np.asarray(ema_arr, dtype=float),
        "fixed_alarm": np.asarray(fix_arr, dtype=int),
        "slope_alarm": np.asarray(slp_arr, dtype=int),
        "hi_thr": np.asarray([hi_thr], dtype=float),
    }


def replay_stream(
    lib: ctypes.CDLL,
    HiFeatures: type,
    samples: np.ndarray,
    fs_hz: float,
    mode: str,
    speed: float = 1.0,
    live_callback: Any = None,
) -> dict[str, Any]:
    """Push 512-sample hops into caller-owned C hi_stream_t via ctypes."""
    assert samples.dtype == np.float32 and samples.ndim == 1
    st_buf = ctypes.create_string_buffer(lib.hi_stream_sizeof())
    st_ptr = ctypes.cast(st_buf, ctypes.c_void_p)
    lib.hi_stream_init_default(st_ptr)

    feats_out = HiFeatures()
    mon_out = HiMonitorOutput()

    hop_dt = HOP_SIZE / fs_hz
    deadline_s = (hop_dt / speed) if mode == "paced" else hop_dt

    hop_latencies_us: list[float] = []
    win_latencies_us: list[float] = []
    deadline_misses = 0
    dropped_samples = 0

    out_raw, out_ema, out_slp, out_gated, out_fix, out_slp_al = [], [], [], [], [], []
    n_hops = len(samples) // HOP_SIZE
    leftover = len(samples) % HOP_SIZE
    if leftover != 0:
        raise ValueError(f"Expected integer multiple of {HOP_SIZE}, got leftover {leftover}")

    next_target = time.perf_counter()
    wall_t0 = next_target
    c_ptr_base = samples.ctypes.data_as(ctypes.POINTER(ctypes.c_float))

    for h in range(n_hops):
        if mode == "paced":
            next_target += hop_dt / speed
            now = time.perf_counter()
            sleep_s = next_target - now
            if sleep_s > 0.0:
                time.sleep(sleep_s)

        offset = h * HOP_SIZE
        chunk_ptr = ctypes.cast(
            ctypes.addressof(c_ptr_base.contents) + offset * ctypes.sizeof(ctypes.c_float),
            ctypes.POINTER(ctypes.c_float),
        )
        t0 = time.perf_counter()
        produced = lib.hi_stream_push(st_ptr, chunk_ptr, HOP_SIZE)
        dt = time.perf_counter() - t0

        dt_us = dt * 1.0e6
        hop_latencies_us.append(dt_us)
        if dt > deadline_s:
            deadline_misses += 1

        if produced > 0:
            win_latencies_us.append(dt_us)
            lib.hi_stream_latest(st_ptr, ctypes.byref(feats_out), ctypes.byref(mon_out))
            out_raw.append(float(mon_out.raw_hi))
            out_ema.append(float(mon_out.ema_hi))
            out_slp.append(float(mon_out.slope))
            out_gated.append(int(mon_out.gated))
            out_fix.append(int(mon_out.fixed_alarm))
            out_slp_al.append(int(mon_out.slope_alarm))
            if live_callback is not None:
                live_callback(out_raw, out_ema, out_gated, out_fix, out_slp_al)

    wall_s = time.perf_counter() - wall_t0
    sim_s = len(samples) / fs_hz
    hop_arr = np.asarray(hop_latencies_us, dtype=float)
    win_arr = np.asarray(win_latencies_us if win_latencies_us else hop_latencies_us, dtype=float)
    return {
        "mode": mode,
        "speed": speed,
        "fs_hz": fs_hz,
        "n_samples": len(samples),
        "n_hops": n_hops,
        "n_outputs": len(out_ema),
        "sim_s": sim_s,
        "wall_s": wall_s,
        "deadline_us": deadline_s * 1.0e6,
        "hop_mean_us": float(hop_arr.mean()),
        "hop_p99_us": float(np.percentile(hop_arr, 99)),
        "hop_max_us": float(hop_arr.max()),
        "out_mean_us": float(win_arr.mean()),
        "out_p99_us": float(np.percentile(win_arr, 99)),
        "out_max_us": float(win_arr.max()),
        "deadline_misses": deadline_misses,
        "dropped_samples": dropped_samples,
        "raw_hi": np.asarray(out_raw, dtype=float),
        "ema_hi": np.asarray(out_ema, dtype=float),
        "slope": np.asarray(out_slp, dtype=float),
        "gated": np.asarray(out_gated, dtype=int),
        "fixed_alarm": np.asarray(out_fix, dtype=int),
        "slope_alarm": np.asarray(out_slp_al, dtype=int),
    }


def save_scenario_plots(
    res: dict[str, Any],
    threshold: float,
    title: str,
    x_label: str,
    annotations: list[tuple[int, str, str]],
    png_path: Path,
    gif_path: Path,
    eval_start: int = 0,
    note_point: tuple[int, str] | None = None,
) -> None:
    """Save static PNG and animated GIF replay view."""
    from matplotlib import pyplot as plt
    from matplotlib.animation import FuncAnimation, PillowWriter

    png_path.parent.mkdir(parents=True, exist_ok=True)
    n = res["n_outputs"]
    x = np.arange(n)
    raw = res["raw_hi"]
    ema = res["ema_hi"]
    gated = res["gated"] == 1
    fix = (res["fixed_alarm"] == 1) & (x >= eval_start)
    slp = (res["slope_alarm"] == 1) & (x >= eval_start)

    # Static full PNG
    fig, ax = plt.subplots(figsize=(12, 4.7))
    ymax = max(float(max(raw.max(), ema.max(), threshold)) * 1.15, threshold * 1.35)
    if eval_start > 0:
        ax.axvspan(0, eval_start - 1, color="#EAEAEA", alpha=0.85,
                   label=f"Baseline/cal (0..{eval_start - 1}, not evaluated)")
    for idx_v, text, col in annotations:
        ax.axvline(idx_v, color=col, ls=":", lw=1.2, label=text)
    if gated.any():
        ax.fill_between(x, 0.0, ymax, where=gated, color="#FFE6CC", alpha=0.7, label="Machine-off gated")
    ax.plot(x, raw, color="#B0B0B0", lw=0.8, alpha=0.8, label="Raw log1p HI")
    ax.plot(x, ema, color="#0072B2", lw=1.6, label="EMA HI (alpha=0.1)")
    ax.axhline(threshold, color="#D55E00", ls="--", lw=1.1, label=f"Fixed threshold ({threshold:.3f})")

    if fix.any():
        ax.scatter(x[fix][::max(1, int(fix.sum()) // 20)], ema[fix][::max(1, int(fix.sum()) // 20)],
                   color="#D55E00", s=24, zorder=5, label=f"Fixed alarm (first@{int(x[fix][0])})")
    if slp.any():
        first_s = int(x[slp][0])
        ax.axvline(first_s, color="#009E73", ls="-.", lw=1.2, label=f"Slope alarm first@{first_s}")
    if note_point is not None:
        nx, ntxt = note_point
        ax.annotate(
            ntxt,
            xy=(nx, float(raw[nx])),
            xytext=(nx + 8, min(ymax * 0.78, float(raw[nx]) + 0.65)),
            arrowprops=dict(arrowstyle="->", color="#444444", lw=0.9),
            fontsize=7.5,
            bbox=dict(boxstyle="round,pad=0.25", fc="white", ec="#888888", alpha=0.92),
        )

    ax.set_title(title, fontsize=10.5, loc="left")
    ax.set_xlabel(x_label, fontsize=9)
    ax.set_ylabel("log1p HI", fontsize=9)
    ax.set_xlim(0, max(1, n - 1))
    ax.set_ylim(0.0, ymax)
    ax.grid(alpha=0.25, lw=0.5)
    ax.legend(fontsize=7.5, loc="upper left", ncol=2)
    fig.tight_layout()
    fig.savefig(png_path, dpi=150, bbox_inches="tight")
    plt.close(fig)

    # Animated GIF (35 evenly spaced frames)
    fig_a, ax_a = plt.subplots(figsize=(10.5, 4.3))
    ax_a.set_title(title, fontsize=9.5, loc="left")
    ax_a.set_xlabel(x_label, fontsize=8.5)
    ax_a.set_ylabel("log1p HI", fontsize=8.5)
    ax_a.set_xlim(0, max(1, n - 1))
    ax_a.set_ylim(0.0, ymax)
    ax_a.grid(alpha=0.25, lw=0.5)
    if eval_start > 0:
        ax_a.axvspan(0, eval_start - 1, color="#EAEAEA", alpha=0.85,
                     label=f"Baseline/cal (0..{eval_start - 1}, not evaluated)")
    for idx_v, text, col in annotations:
        ax_a.axvline(idx_v, color=col, ls=":", lw=1.0, label=text)
    if gated.any():
        ax_a.fill_between(x, 0.0, ymax, where=gated, color="#FFE6CC", alpha=0.6, label="Machine-off gated")
    ax_a.axhline(threshold, color="#D55E00", ls="--", lw=1.0, label=f"Threshold ({threshold:.3f})")
    if note_point is not None:
        nx, ntxt = note_point
        ax_a.annotate(
            ntxt,
            xy=(nx, float(raw[nx])),
            xytext=(nx + 8, min(ymax * 0.78, float(raw[nx]) + 0.65)),
            arrowprops=dict(arrowstyle="->", color="#444444", lw=0.8),
            fontsize=7,
            bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="#888888", alpha=0.92),
        )
    (line_raw,) = ax_a.plot([], [], color="#B0B0B0", lw=0.8, alpha=0.8, label="Raw HI")
    (line_ema,) = ax_a.plot([], [], color="#0072B2", lw=1.6, label="EMA HI")
    (pts_fix,) = ax_a.plot([], [], "o", color="#D55E00", ms=4, label="Post-cal fixed alarm" if eval_start > 0 else "Fixed alarm")
    ax_a.legend(fontsize=7, loc="upper left", ncol=2)
    fig_a.tight_layout()

    steps = sorted(set(np.linspace(1, n, min(36, n), dtype=int).tolist()))

    def _update(end_k: int) -> tuple[Any, ...]:
        line_raw.set_data(x[:end_k], raw[:end_k])
        line_ema.set_data(x[:end_k], ema[:end_k])
        m = fix[:end_k]
        pts_fix.set_data(x[:end_k][m][::max(1, int(m.sum()) // 15)], ema[:end_k][m][::max(1, int(m.sum()) // 15)])
        return line_raw, line_ema, pts_fix

    anim = FuncAnimation(fig_a, _update, frames=steps, blit=False, interval=90)
    anim.save(gif_path, writer=PillowWriter(fps=11))
    plt.close(fig_a)


def run_live_view(
    lib: ctypes.CDLL,
    HiFeatures: type,
    samples: np.ndarray,
    fs_hz: float,
    threshold: float,
    title: str,
    speed: float,
) -> None:
    """Interactive live matplotlib window (pass --live --scenario ...)."""
    from matplotlib import pyplot as plt

    plt.ion()
    fig, ax = plt.subplots(figsize=(11, 4.5))
    ax.axhline(threshold, color="#D55E00", ls="--", lw=1.0, label=f"Threshold ({threshold:.3f})")
    (lr,) = ax.plot([], [], color="#B0B0B0", lw=0.8, label="Raw HI")
    (le,) = ax.plot([], [], color="#0072B2", lw=1.6, label="EMA HI")
    (pf,) = ax.plot([], [], "o", color="#D55E00", ms=4, label="Fixed alarm")
    ax.set_title(title, fontsize=10)
    ax.set_xlabel("Output step")
    ax.set_ylabel("log1p HI")
    ax.legend(loc="upper left", fontsize=8)
    ax.grid(alpha=0.25)

    def _cb(raw: list[float], ema: list[float], _g: list[int], fix: list[int], _s: list[int]) -> None:
        n = len(ema)
        if n % 4 != 0 and n > 20:
            return
        xs = np.arange(n)
        lr.set_data(xs, raw)
        le.set_data(xs, ema)
        fa = np.asarray(fix, dtype=bool)
        pf.set_data(xs[fa], np.asarray(ema)[fa])
        ax.set_xlim(0, max(20, n))
        ax.set_ylim(0.0, max(threshold * 1.4, max(ema) * 1.15))
        plt.pause(0.001)

    res = replay_stream(lib, HiFeatures, samples, fs_hz, "paced", speed=speed, live_callback=_cb)
    plt.ioff()
    print(f"[LIVE] completed outputs={res['n_outputs']}, wall={res['wall_s']:.2f}s, misses={res['deadline_misses']}")
    plt.show()


def check_parity(name: str, c_res: dict[str, Any], py_ref: dict[str, np.ndarray]) -> str:
    n = c_res["n_outputs"]
    assert n == len(py_ref["ema_hi"]), f"{name}: len mismatch {n} vs {len(py_ref['ema_hi'])}"
    max_raw = float(np.max(np.abs(c_res["raw_hi"] - py_ref["raw_hi"])))
    max_ema = float(np.max(np.abs(c_res["ema_hi"] - py_ref["ema_hi"])))
    gate_eq = int(np.sum(c_res["gated"] == py_ref["gated"]))
    fix_eq = int(np.sum(c_res["fixed_alarm"] == py_ref["fixed_alarm"]))
    slp_eq = int(np.sum(c_res["slope_alarm"] == py_ref["slope_alarm"]))
    return (
        f"parity vs Python: max_abs(raw)={max_raw:.2e}, max_abs(ema)={max_ema:.2e}, "
        f"gated={gate_eq}/{n}, fixed_alarm={fix_eq}/{n}, slope_alarm={slp_eq}/{n}"
    )


def format_run_line(tag: str, r: dict[str, Any], parity_str: str) -> str:
    ff = np.flatnonzero(r["fixed_alarm"])
    fs = np.flatnonzero(r["slope_alarm"])
    return (
        f"  [{tag:<11}] sim={r['sim_s']:6.2f}s wall={r['wall_s']:6.3f}s | "
        f"hop_us(mean/p99/max)={r['hop_mean_us']:5.1f}/{r['hop_p99_us']:5.1f}/{r['hop_max_us']:6.1f} | "
        f"out_us(mean/p99/max)={r['out_mean_us']:5.1f}/{r['out_p99_us']:5.1f}/{r['out_max_us']:6.1f} | "
        f"dl={r['deadline_us']:7.1f}us miss={r['deadline_misses']}/{r['n_hops']} drop={r['dropped_samples']} | "
        f"first(fix={int(ff[0]) if ff.size else 'none'}, slp={int(fs[0]) if fs.size else 'none'}) | {parity_str}"
    )


